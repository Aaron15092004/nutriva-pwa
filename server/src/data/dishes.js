const slug = (s) =>
  s.toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/đ/g, 'd').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// D(bữa, nhóm món, tag, tên, nguyên liệu, ảnh?)
const D = (meal, category, tag, name, ingredients, image) => ({ key: slug(name), meal, category, tag, name, ingredients, image });
