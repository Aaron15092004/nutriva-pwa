export const foodImageKey = (food) => {
  const name = String(food?.name ?? '').toLowerCase().trim();
  return RULES.find(([re]) => re.test(name))?.[1] ?? GROUP[food?.group] ?? 'porridge';
};
export const foodImage = (food) => food?.image || `/img/foods/${foodImageKey(food)}.webp`;

